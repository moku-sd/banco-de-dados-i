CREATE TABLE usuario (
    id_usuario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    gamertag       VARCHAR(30)  NOT NULL,
    data_cadastro  TIMESTAMP    NOT NULL DEFAULT now(),          -- RN02
    CONSTRAINT uq_usuario_email    UNIQUE (email),               -- RN01
    CONSTRAINT uq_usuario_gamertag UNIQUE (gamertag)             -- RN01
);

CREATE TABLE desenvolvedora (
    id_desenvolvedora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(100) NOT NULL,
    pais              VARCHAR(60),
    ano_fundacao      SMALLINT
);

CREATE TABLE publicadora (
    id_publicadora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    pais           VARCHAR(60),
    ano_fundacao   SMALLINT
);

CREATE TABLE genero (
    id_genero INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(50) NOT NULL,
    CONSTRAINT uq_genero_nome UNIQUE (nome)
);

CREATE TABLE plataforma (
    id_plataforma  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(50) NOT NULL,
    ano_lancamento SMALLINT,
    CONSTRAINT uq_plataforma_nome UNIQUE (nome)
);

CREATE TABLE jogo (
    id_jogo           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo            VARCHAR(150) NOT NULL,
    descricao         TEXT,
    data_lancamento   DATE         NOT NULL,
    id_desenvolvedora INTEGER      NOT NULL,                     -- RN03
    id_publicadora    INTEGER      NOT NULL,                     -- RN03
    CONSTRAINT fk_jogo_desenvolvedora FOREIGN KEY (id_desenvolvedora)
        REFERENCES desenvolvedora (id_desenvolvedora) ON DELETE RESTRICT,  -- RN19
    CONSTRAINT fk_jogo_publicadora FOREIGN KEY (id_publicadora)
        REFERENCES publicadora (id_publicadora) ON DELETE RESTRICT         -- RN19
);

CREATE TABLE jogo_genero (
    id_jogo   INTEGER NOT NULL,
    id_genero INTEGER NOT NULL,
    PRIMARY KEY (id_jogo, id_genero),
    CONSTRAINT fk_jogo_genero_jogo FOREIGN KEY (id_jogo)
        REFERENCES jogo (id_jogo) ON DELETE CASCADE,                       -- RN20
    CONSTRAINT fk_jogo_genero_genero FOREIGN KEY (id_genero)
        REFERENCES genero (id_genero) ON DELETE RESTRICT                   -- RN19
);

CREATE TABLE jogo_plataforma (
    id_jogo_plataforma         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jogo                    INTEGER NOT NULL,
    id_plataforma              INTEGER NOT NULL,
    data_lancamento_plataforma DATE,
    CONSTRAINT uq_jogo_plataforma UNIQUE (id_jogo, id_plataforma),
    CONSTRAINT fk_jogo_plataforma_jogo FOREIGN KEY (id_jogo)
        REFERENCES jogo (id_jogo) ON DELETE CASCADE,                       -- RN20
    CONSTRAINT fk_jogo_plataforma_plataforma FOREIGN KEY (id_plataforma)
        REFERENCES plataforma (id_plataforma) ON DELETE RESTRICT           -- RN19
);

CREATE TABLE pacote_conquistas (
    id_pacote          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jogo_plataforma INTEGER      NOT NULL,
    nome               VARCHAR(100) NOT NULL,
    tipo               VARCHAR(10)  NOT NULL,
    data_lancamento    DATE         NOT NULL,
    CONSTRAINT ck_pacote_tipo CHECK (tipo IN ('BASE', 'DLC', 'UPDATE')),   -- RN06
    CONSTRAINT fk_pacote_jogo_plataforma FOREIGN KEY (id_jogo_plataforma)
        REFERENCES jogo_plataforma (id_jogo_plataforma) ON DELETE CASCADE  -- RN20
