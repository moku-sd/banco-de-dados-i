    CONSTRAINT uq_item_usuario_jogo_plataforma
        UNIQUE (id_usuario, id_jogo_plataforma),                           -- RN11
    CONSTRAINT ck_item_status CHECK (status IN
        ('QUERO_JOGAR', 'JOGANDO', 'PAUSADO', 'ABANDONADO', 'FINALIZADO')),-- RN12
    CONSTRAINT ck_item_horas CHECK (horas_jogadas >= 0),                   -- RN13
    CONSTRAINT fk_item_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,                 -- RN21
    CONSTRAINT fk_item_jogo_plataforma FOREIGN KEY (id_jogo_plataforma)
        REFERENCES jogo_plataforma (id_jogo_plataforma) ON DELETE CASCADE  -- RN20
);

