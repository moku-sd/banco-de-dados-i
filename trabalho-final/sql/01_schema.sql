CREATE TABLE conquista (
    id_conquista INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pacote    INTEGER      NOT NULL,
    nome         VARCHAR(100) NOT NULL,
    descricao    TEXT         NOT NULL,
    gamerscore   INTEGER      NOT NULL,
    CONSTRAINT ck_conquista_gamerscore CHECK (gamerscore > 0),             -- RN07
    CONSTRAINT fk_conquista_pacote FOREIGN KEY (id_pacote)
        REFERENCES pacote_conquistas (id_pacote) ON DELETE CASCADE         -- RN20
