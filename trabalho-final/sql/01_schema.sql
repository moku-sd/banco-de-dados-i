-- Limite de gamerscore por tipo de pacote (RN08 / RN09)
CREATE FUNCTION fn_limite_gamerscore(p_tipo VARCHAR) RETURNS INTEGER AS $$
    SELECT CASE WHEN p_tipo = 'BASE' THEN 1000 ELSE 250 END;
$$ LANGUAGE sql IMMUTABLE;

-- T1 (RN14): a conquista desbloqueada deve pertencer ao mesmo
-- jogo/plataforma do item da biblioteca.
CREATE FUNCTION fn_t1_desbloqueio_mesmo_jogo_plataforma() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM item_biblioteca ib
          JOIN conquista c          ON c.id_conquista = NEW.id_conquista
          JOIN pacote_conquistas pc ON pc.id_pacote   = c.id_pacote
         WHERE ib.id_item = NEW.id_item
           AND pc.id_jogo_plataforma = ib.id_jogo_plataforma
    ) THEN
        RAISE EXCEPTION 'RN14: a conquista % não pertence ao jogo/plataforma do item de biblioteca % (ou um deles não existe)',
            NEW.id_conquista, NEW.id_item
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_t1_desbloqueio_mesmo_jogo_plataforma
    BEFORE INSERT OR UPDATE OF id_item, id_conquista ON desbloqueio
    FOR EACH ROW EXECUTE FUNCTION fn_t1_desbloqueio_mesmo_jogo_plataforma();

-- T1 (complemento): impede trocar o vínculo jogo/plataforma de um item,
-- pacote ou conquista que já possui desbloqueios, o que quebraria a RN14.
CREATE FUNCTION fn_t1_protege_item() RETURNS trigger AS $$
BEGIN
    IF NEW.id_jogo_plataforma IS DISTINCT FROM OLD.id_jogo_plataforma
       AND EXISTS (SELECT 1 FROM desbloqueio WHERE id_item = OLD.id_item) THEN
        RAISE EXCEPTION 'RN14: o item de biblioteca % possui desbloqueios; não é possível alterar o jogo/plataforma', OLD.id_item
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION fn_t1_protege_conquista() RETURNS trigger AS $$
BEGIN
    IF NEW.id_pacote IS DISTINCT FROM OLD.id_pacote
       AND EXISTS (SELECT 1 FROM desbloqueio WHERE id_conquista = OLD.id_conquista) THEN
        RAISE EXCEPTION 'RN14: a conquista % possui desbloqueios; não é possível mudá-la de pacote', OLD.id_conquista
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION fn_t1_protege_pacote() RETURNS trigger AS $$
BEGIN
    IF NEW.id_jogo_plataforma IS DISTINCT FROM OLD.id_jogo_plataforma
       AND EXISTS (SELECT 1 FROM conquista c
                     JOIN desbloqueio d ON d.id_conquista = c.id_conquista
                    WHERE c.id_pacote = OLD.id_pacote) THEN
        RAISE EXCEPTION 'RN14: o pacote % possui conquistas desbloqueadas; não é possível alterar o jogo/plataforma', OLD.id_pacote
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_t1_protege_item
    BEFORE UPDATE OF id_jogo_plataforma ON item_biblioteca
    FOR EACH ROW EXECUTE FUNCTION fn_t1_protege_item();
CREATE TRIGGER trg_t1_protege_conquista
    BEFORE UPDATE OF id_pacote ON conquista
    FOR EACH ROW EXECUTE FUNCTION fn_t1_protege_conquista();
CREATE TRIGGER trg_t1_protege_pacote
    BEFORE UPDATE OF id_jogo_plataforma ON pacote_conquistas
    FOR EACH ROW EXECUTE FUNCTION fn_t1_protege_pacote();

-- T2 (RN15): a data/hora do desbloqueio não pode ser futura.
CREATE FUNCTION fn_t2_data_hora_nao_futura() RETURNS trigger AS $$
BEGIN
    IF NEW.data_hora > LOCALTIMESTAMP THEN
        RAISE EXCEPTION 'RN15: a data/hora do desbloqueio (%) não pode ser futura', NEW.data_hora
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_t2_data_hora_nao_futura
    BEFORE INSERT OR UPDATE OF data_hora ON desbloqueio
    FOR EACH ROW EXECUTE FUNCTION fn_t2_data_hora_nao_futura();

-- T3 (RN08 / RN09): a soma do gamerscore de um pacote não pode exceder
-- 1000 G (BASE) ou 250 G (DLC/UPDATE). A igualdade a 1000 G no pacote
-- BASE é verificada pela visão vw_auditoria_integridade.
CREATE FUNCTION fn_t3_gamerscore_conquista() RETURNS trigger AS $$
DECLARE
    v_tipo   VARCHAR(10);
    v_outras INTEGER;
BEGIN
    -- trava o pacote para serializar inserções concorrentes na mesma soma
    SELECT tipo INTO v_tipo FROM pacote_conquistas
     WHERE id_pacote = NEW.id_pacote FOR UPDATE;
    IF NOT FOUND THEN
        RETURN NEW;                      -- a FK reportará o erro
    END IF;

    SELECT COALESCE(SUM(gamerscore), 0) INTO v_outras
      FROM conquista
     WHERE id_pacote = NEW.id_pacote AND id_conquista <> NEW.id_conquista;

    IF v_outras + NEW.gamerscore > fn_limite_gamerscore(v_tipo) THEN
        RAISE EXCEPTION 'RN08/RN09: o pacote % (%) excederia % G (soma atual: % G + nova conquista: % G)',
            NEW.id_pacote, v_tipo, fn_limite_gamerscore(v_tipo), v_outras, NEW.gamerscore
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_t3_gamerscore_conquista
    BEFORE INSERT OR UPDATE OF gamerscore, id_pacote ON conquista
    FOR EACH ROW EXECUTE FUNCTION fn_t3_gamerscore_conquista();

-- T3 (complemento): ao mudar o tipo de um pacote, o novo limite também
-- precisa ser respeitado pela soma já existente.
CREATE FUNCTION fn_t3_tipo_pacote() RETURNS trigger AS $$
DECLARE
    v_soma INTEGER;
BEGIN
    SELECT COALESCE(SUM(gamerscore), 0) INTO v_soma
      FROM conquista WHERE id_pacote = NEW.id_pacote;
    IF v_soma > fn_limite_gamerscore(NEW.tipo) THEN
        RAISE EXCEPTION 'RN08/RN09: o pacote % possui % G, acima do limite de % G para o tipo %',
            NEW.id_pacote, v_soma, fn_limite_gamerscore(NEW.tipo), NEW.tipo
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_t3_tipo_pacote
    BEFORE UPDATE OF tipo ON pacote_conquistas
    FOR EACH ROW EXECUTE FUNCTION fn_t3_tipo_pacote();

-- ---------------------------------------------------------------------
-- 4. VISÃO DE AUDITORIA
--    Regras de completude ("exatamente 1000 G", "ao menos um") que não
--    podem ser impostas a cada inserção isolada. Linhas retornadas
--    indicam violações; resultado vazio = banco consistente.
-- ---------------------------------------------------------------------
CREATE VIEW vw_auditoria_integridade AS
SELECT 'RN08'::VARCHAR(10) AS regra,
       'Pacote BASE com gamerscore total diferente de 1000'::TEXT AS problema,
       ('pacote ' || pc.id_pacote || ' (' || pc.nome || '): '
            || COALESCE(SUM(c.gamerscore), 0) || ' G')::TEXT AS referencia
  FROM pacote_conquistas pc
  LEFT JOIN conquista c ON c.id_pacote = pc.id_pacote
 WHERE pc.tipo = 'BASE'
 GROUP BY pc.id_pacote, pc.nome
HAVING COALESCE(SUM(c.gamerscore), 0) <> 1000
UNION ALL
SELECT 'RN06', 'Jogo/plataforma sem pacote BASE',
       'jogo_plataforma ' || jp.id_jogo_plataforma || ' (' || j.titulo || ' / ' || p.nome || ')'
  FROM jogo_plataforma jp
  JOIN jogo j       ON j.id_jogo = jp.id_jogo
  JOIN plataforma p ON p.id_plataforma = jp.id_plataforma
 WHERE NOT EXISTS (SELECT 1 FROM pacote_conquistas pc
                    WHERE pc.id_jogo_plataforma = jp.id_jogo_plataforma AND pc.tipo = 'BASE')
UNION ALL
SELECT 'RN04', 'Jogo sem gênero', 'jogo ' || j.id_jogo || ' (' || j.titulo || ')'
  FROM jogo j
 WHERE NOT EXISTS (SELECT 1 FROM jogo_genero jg WHERE jg.id_jogo = j.id_jogo)
UNION ALL
SELECT 'RN04', 'Jogo sem plataforma', 'jogo ' || j.id_jogo || ' (' || j.titulo || ')'
  FROM jogo j
 WHERE NOT EXISTS (SELECT 1 FROM jogo_plataforma jp WHERE jp.id_jogo = j.id_jogo)
UNION ALL
SELECT 'RN22', 'Recomendação sem nenhum jogo', 'recomendacao ' || r.id_recomendacao
  FROM recomendacao r
 WHERE NOT EXISTS (SELECT 1 FROM recomendacao_jogo rj WHERE rj.id_recomendacao = r.id_recomendacao);
